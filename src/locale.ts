export function translate(locale: Locale, source: string, values: readonly unknown[] = []) {
  const text = locale === "en" && Object.hasOwn(en, source) ? en[source]! : source;
  return values.length ? text.replace(/\{(\d+)\}/g, (_, i) => String(values[Number(i)])) : text;
}

export function useLocale() {
  const { locale, setLocale } = useContext(LocaleContext);
  return { locale, setLocale, t: (source: string, values?: readonly unknown[]) => translate(locale, source, values) };
}

// Only used for app-generated notices and errors already formatted by the backend.
const serverFormats = Object.keys(en).filter((key) => key.includes("{") && [
  "Chỉ gửi", '"{0}" vượt', "Tin nhắn thoại vượt", "điện thoại báo lỗi", "Đang tải bản sao lưu",
  "tải thất bại", "giải mã thất bại", "Đã nhập", "Đồng bộ thất bại",
].some((start) => key.startsWith(start))).map((key) => ({
  key,
  pattern: new RegExp("^" + key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/\\\{\d+\\\}/g, "(.+?)") + "$"),
}));

export function localizeNotice(locale: Locale, text: string): string {
  if (locale === "vi" || Object.hasOwn(en, text)) return translate(locale, text);
  for (const { key, pattern } of serverFormats) {
    const match = text.match(pattern);
    if (match) {
      const values = match.slice(1);
      if (key === "Đồng bộ thất bại: {0}") values[0] = localizeNotice(locale, values[0]!);
      return translate(locale, key, values);
    }
  }
  return text;
}
